"""
pixelart/base_maps.py -- Hand-authored 16x16 pixel matrices (blocks).

Each map below is a character grid I placed by hand, glyph by glyph:

    H  specular highlight        L  key light (always biased top-left)
    M  mid / body tone           D  form shadow (faces turning away)
    S  ambient occlusion         O  1px dark outline / deepest crevice
    C  mineral emissive core     g  mineral glow falloff
    T  translucent / alpha edge  .  transparent

Golden Rule #3 compliance is authored in, not applied afterwards:
    * every block has a 1px 'O' contour where elements meet,
    * dithering is explicit stipple -- isolated single glyphs, hand-placed,
    * ambient occlusion sits in the crevices and under overhangs,
    * the top-left quadrant carries H/L, the bottom-right carries D/S.

NO shape functions are used anywhere. What you see below IS the texture.
"""

