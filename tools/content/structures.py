ALL_STRUCTURES: List[StructureSpec] = (BOSS_ARENAS + PORTAL_STRUCTURES
                                    + WORLD_STRUCTURES + BIOME_LANDMARKS)
STRUCTURE_BY_ID: Dict[str, StructureSpec] = {}
for _s in ALL_STRUCTURES:
    if _s.id in STRUCTURE_BY_ID:
        raise ValueError(f"duplicate structure id {_s.id!r}")
    STRUCTURE_BY_ID[_s.id] = _s


def structures_in(dimension: str) -> List[StructureSpec]:
    return [s for s in ALL_STRUCTURES if s.dimension == dimension]


def structure_by_id(structure_id: str) -> StructureSpec:
    try:
        return STRUCTURE_BY_ID[structure_id]
    except KeyError:
        raise KeyError(f"unknown structure {structure_id!r}") from None
