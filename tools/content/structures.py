"""
content/structures.py -- 115 structures.

Jigsaw-driven, data-driven. Each entry declares its placement rules, the
biomes it can generate in, its jigsaw pool root and its loot tables (which
always include a custom lore book -- Golden Rule: no structure without lore).

Five of these are the boss arenas: 2 in the Overworld, 3 across the dimensions.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Dict, List, Optional, Tuple


@dataclass(frozen=True)
class StructureSpec:
    id: str
    name: str
    dimension: str
    kind: str                      # jigsaw | terrain_adaptation | surface | underground | nether_fossil_style
    step: str                      # generation step (surface_structures, underground_structures, ...)
    terrain_adaptation: str        # none | beard_thin | beard_box | bury | encasing
    spacing: int                   # average chunks between attempts
    separation: int                # minimum chunks between attempts
    salt: int
    start_height: int              # absolute Y of the jigsaw root
    start_jigsaw_pool: str         # pool id under worldgen/template_pool
    max_depth: int
    biomes: Tuple[str, ...]
    loot_tables: Tuple[str, ...]
    lore_book: str
    is_boss_arena: bool = False
    boss: Optional[str] = None
    use_expansion_hash: bool = True
    liquid_settings: str = "apply_waterlogging"
    lore: str = ""

    def __post_init__(self) -> None:
        if self.separation >= self.spacing:
            raise ValueError(
                f"structure {self.id!r}: separation ({self.separation}) must be < spacing ({self.spacing})"
            )
        if not self.loot_tables:
            raise ValueError(f"structure {self.id!r}: Golden Rule - every structure needs loot tables")
        if not self.lore_book:
            raise ValueError(f"structure {self.id!r}: Golden Rule - every structure needs a lore book")
        if self.is_boss_arena and not self.boss:
            raise ValueError(f"structure {self.id!r}: boss arena must name its boss")

    @property
    def structure_id(self) -> str:
        return f"biomesunseen:{self.id}"

    @property
    def pool_id(self) -> str:
        return f"biomesunseen:{self.start_jigsaw_pool}"


