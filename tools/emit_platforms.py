def _loom_for(mc):
    parts = mc.split(".")
    major = int(parts[0])
    if major >= 26:
        return LOOM_VERSION_NEW
    if len(parts) >= 3 and int(parts[1]) == 21 and int(parts[2]) >= 6:
        return LOOM_VERSION_MID
    return LOOM_VERSION
