def _gradle_props(F, mc, java, loader, arch, geckolib, cloth, loader_ver,
                  fabric_api, forge, neoforge, loom_ver):
    lines = [
        "# Auto-generated by tools/generate.py - one target: %s / %s" % (loader, mc),
        "mod_id=biomesunseen",
        "mod_name=Biomes Unseen",
        "mod_version=%s" % MOD_VERSION,
        "mod_group=com.biomesunseen",
        "minecraft_version=%s" % mc,
        "target_java=%d" % java,
        "loader=%s" % loader,
        "loom.platform=%s" % loader,
        "loom_version=%s" % loom_ver,
        "architectury_version=%s" % arch,
    ]
    if loader == "fabric":
        lines.append("fabric_loader_version=%s" % loader_ver)
        lines.append("fabric_api_version=%s" % fabric_api)
        lines.append("yarn_mappings=%s" % YARN_VERSIONS[mc])
    elif loader == "forge":
        lines.append("forge_version=%s" % forge)
    else:
        lines.append("neoforge_version=%s" % neoforge)
    if geckolib:
        lines.append("geckolib_version=%s" % geckolib)
    lines.append("cloth_config_version=%s" % cloth)
    return "\n".join(lines) + "\n"


