def _mc_num(mc):
    """(1, 21, 5) for "1.21.5"; "26.1" becomes (26, 1, 0)."""
    out = []
    for part in str(mc).split(".")[:3]:
        try:
            out.append(int(part))
        except ValueError:
            out.append(0)
    while len(out) < 3:
        out.append(0)
    return tuple(out)


