def sound_files():
    with open(os.path.join(ASSETS, "sounds.json"), "r", encoding="utf-8") as fh:
        spec = json.load(fh)
    paths = []
    for entry in spec.values():
        for sound in entry["sounds"]:
            name = sound["name"] if isinstance(sound, dict) else sound
            namespace, _, path = name.partition(":")
            if namespace == NAMESPACE:
                paths.append(os.path.join(ASSETS, "sounds", *path.split("/")) + ".ogg")
    return sorted(set(paths))


def main():
    data = base64.b64decode("".join(SILENT_OGG_B64.split()))
    if data[:4] != b"OggS" or b"\x01vorbis" not in data[:64]:
        raise SystemExit("embedded clip is not a valid Ogg Vorbis stream")
    files = sound_files()
    for path in files:
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "wb") as fh:
            fh.write(data)
    print("wrote %d silent .ogg file(s)" % len(files))


if __name__ == "__main__":
    main()
