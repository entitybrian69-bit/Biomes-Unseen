#!/usr/bin/env python3
"""Generates ores from tools/spec/ores.py (standard library only).

Writes:
  tools/texdata/gen_ores_NN.py             block + item sprites (literal hex matrices)
  data/biomesunseen/specs/ores.json        read by the Java registries (43 generated ores)
  data/biomesunseen/worldgen/configured_feature/ore_<id>.json  (all 44 ores)
  data/biomesunseen/worldgen/placed_feature/ore_<id>.json
  data/biomesunseen/forge/biome_modifier/ore_<id>.json
Hollow Deep ores target #biomesunseen:hollow_deep (written by tools/gen_biomes.py: run it first).
Usage: python tools/gen_ores.py
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from jsonfmt import write  # noqa: E402
from modelkit import emit_sprite  # noqa: E402
from spec.oregrids import BLOCKS, ITEMS  # noqa: E402
from spec.ores import HOLLOWITE, ORES  # noqa: E402
from spec.palettes import GLOWS, HOSTS, PALETTES  # noqa: E402

ROOT = os.path.dirname(HERE)
DATA = os.path.join(ROOT, "src", "main", "resources", "data", "biomesunseen")
SHARD = 8
XP = {0: (0, 2), 1: (1, 4), 2: (3, 7)}
DROPS = {"gem": (1, 1), "ingot": (1, 1), "crystal": (1, 2), "orb": (1, 1), "shard": (1, 3), "nugget": (2, 4)}
STYLE_NAME = {"gem": "Gem", "ingot": "Ingot", "crystal": "Crystal", "orb": "Orb", "shard": "Shard", "nugget": "Nugget"}


def block_sprite(host, layout, pal, glow):
    o, h, m, d = HOSTS[host]
    k, x, c = PALETTES[pal][0], PALETTES[pal][2], PALETTES[pal][3]
    ramp = {"O": o, "h": h, "m": m, "d": d, "k": k, "x": x, "c": c, "l": GLOWS[glow][1]}
    return [[ramp[ch] for ch in row] for row in BLOCKS[layout]]


def item_sprite(style, pal, glow):
    o, a, b, c = PALETTES[pal]
    ramp = {".": None, "O": o, "w": GLOWS[glow][1], "l": c, "c": b, "d": a}
    return [[ramp[ch] for ch in row] for row in ITEMS[style]]


def worldgen(row):
    oid, vein, count, ymin, ymax, dim = row[0], row[8], row[9], row[10], row[11], row[12]
    block = {"Name": "biomesunseen:%s_ore" % oid}
    write(os.path.join(DATA, "worldgen", "configured_feature", "ore_%s.json" % oid), {
        "type": "minecraft:ore", "config": {"size": vein, "discard_chance_on_air_exposure": 0.0, "targets": [
            {"target": {"predicate_type": "minecraft:tag_match", "tag": "minecraft:stone_ore_replaceables"}, "state": block},
            {"target": {"predicate_type": "minecraft:tag_match", "tag": "minecraft:deepslate_ore_replaceables"}, "state": block}]}})
    write(os.path.join(DATA, "worldgen", "placed_feature", "ore_%s.json" % oid), {
        "feature": "biomesunseen:ore_" + oid,
        "placement": [{"type": "minecraft:count", "count": count}, {"type": "minecraft:in_square"},
                      {"type": "minecraft:height_range", "height": {"type": "minecraft:uniform",
                       "min_inclusive": {"absolute": ymin}, "max_inclusive": {"absolute": ymax}}},
                      {"type": "minecraft:biome"}]})
    write(os.path.join(DATA, "forge", "biome_modifier", "ore_%s.json" % oid), {
        "type": "forge:add_features",
        "biomes": "#minecraft:is_overworld" if dim == "ow" else "#biomesunseen:hollow_deep",
        "features": "biomesunseen:ore_" + oid, "step": "underground_ores"})


def main():
    sprites, specs = [], []
    for row in ORES:
        oid, name, style, pal, glow, host, layout, tier, _v, _c, _lo, _hi, dim = row
        assert style in ITEMS and layout in BLOCKS and host in HOSTS and pal in PALETTES and glow in GLOWS, oid
        item = "%s_%s" % (oid, style)
        sprites.append(("block/%s_ore" % oid, block_sprite(host, layout, pal, glow)))
        sprites.append(("item/" + item, item_sprite(style, pal, glow)))
        lo, hi = DROPS[style]
        specs.append({"id": oid, "name": name, "item": item, "itemName": "%s %s" % (name, STYLE_NAME[style]),
                      "tier": tier, "hardness": 3.0 + tier, "light": 4 if host == "dark" else 0,
                      "xpMin": XP[tier][0], "xpMax": XP[tier][1], "dropMin": lo, "dropMax": hi})
        worldgen(row)
    worldgen(HOLLOWITE)
    write(os.path.join(DATA, "specs", "ores.json"), specs, width=400)
    head = '"""Generated by tools/gen_ores.py from tools/spec/ores.py. Do not edit by hand."""\n\nSPRITES = {\n'
    per = SHARD * 2
    for n, i in enumerate(range(0, len(sprites), per), 1):
        body = "\n".join(emit_sprite(k, rows) for k, rows in sprites[i:i + per])
        with open(os.path.join(HERE, "texdata", "gen_ores_%02d.py" % n), "w") as fh:
            fh.write(head + body + "\n}\n")
    print("generated %d ores (+ hollowite worldgen)" % len(specs))


if __name__ == "__main__":
    main()
