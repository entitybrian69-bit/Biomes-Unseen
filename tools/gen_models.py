#!/usr/bin/env python3
"""Generates everything for the 80 spec mobs from tools/spec/mobs.py (standard library only).

Writes:
  assets/biomesunseen/geo/entity/<id>.geo.json and animations/entity/<id>.animation.json
  tools/texdata/gen_mobs_NN.py          (literal hex matrices; run gen_textures.py afterwards)
  data/biomesunseen/specs/mobs.json     (read by the Java registries at startup)
  data/biomesunseen/loot_tables/entities/<id>.json
Usage: python tools/gen_models.py
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from archetypes import ARCHETYPES  # noqa: E402
from jsonfmt import write  # noqa: E402
from modelkit import emit_sprite, geo, hex_int, scale_bones, tile_sheet  # noqa: E402
from spec.mobs import MOBS  # noqa: E402
from spec.palettes import GLOWS, PALETTES  # noqa: E402

ROOT = os.path.dirname(HERE)
RES = os.path.join(ROOT, "src", "main", "resources")
GEO = os.path.join(RES, "assets", "biomesunseen", "geo", "entity")
ANI = os.path.join(RES, "assets", "biomesunseen", "animations", "entity")
DATA = os.path.join(RES, "data", "biomesunseen")
SHARD = 14

# archetype -> (armor, knockback resistance, xp)
DEFAULTS = {"biped": (0, 0.0, 8), "brute": (6, 0.6, 18), "crawler": (0, 0.0, 6), "quad": (0, 0.0, 7),
            "floater": (0, 0.0, 10), "blob": (0, 0.0, 3), "serpent": (0, 0.0, 8)}


def loot(drop):
    item, lo, hi = drop
    return {"type": "minecraft:entity", "pools": [{"rolls": 1, "bonus_rolls": 0, "entries": [{
        "type": "minecraft:item", "name": item,
        "functions": [{"function": "minecraft:set_count", "count": {"type": "minecraft:uniform", "min": lo, "max": hi}},
                      {"function": "minecraft:looting_enchant", "count": {"type": "minecraft:uniform", "min": 0, "max": 1}}]}]}]}


def main():
    specs, sprites = [], []
    for row in MOBS:
        (mid, name, arch, sc, pal, glow, face, hide, acc, hp, dmg, spd, fx, theme, drop) = row
        assert arch in ARCHETYPES and pal in PALETTES and glow in GLOWS, mid
        bones, (hw, hh), anims = ARCHETYPES[arch](acc)
        scale_bones(bones, sc)
        hitbox = (round(hw * sc, 2), round(hh * sc, 2))
        write(os.path.join(GEO, mid + ".geo.json"), geo(mid, bones, 16, 16, hitbox))
        write(os.path.join(ANI, mid + ".animation.json"),
              {"format_version": "1.8.0", "animations": {"animation.%s.%s" % (mid, k): v for k, v in anims.items()}})
        write(os.path.join(DATA, "loot_tables", "entities", mid + ".json"), loot(drop))
        sprites.append(("entity/" + mid, tile_sheet(pal, glow, face, hide)))
        armor, kb, xp = DEFAULTS[arch]
        specs.append({"id": mid, "name": name, "archetype": arch, "theme": theme,
                      "width": hitbox[0], "height": hitbox[1], "health": hp, "damage": dmg, "speed": spd,
                      "armor": armor, "knockback": kb, "xp": xp,
                      "effect": fx[0] if fx else "none", "effectTicks": fx[1] if fx else 0,
                      "effectAmp": fx[2] if fx else 0,
                      "eggPrimary": hex_int(PALETTES[pal][1]), "eggSecondary": hex_int(GLOWS[glow][0])})
    write(os.path.join(DATA, "specs", "mobs.json"), specs, width=400)

    head = '"""Generated by tools/gen_models.py from tools/spec/mobs.py. Do not edit by hand."""\n\nSPRITES = {\n'
    for n, i in enumerate(range(0, len(sprites), SHARD), 1):
        body = "\n".join(emit_sprite(k, rows) for k, rows in sprites[i:i + SHARD])
        with open(os.path.join(HERE, "texdata", "gen_mobs_%02d.py" % n), "w") as fh:
            fh.write(head + body + "\n}\n")
    print("generated %d mobs" % len(specs))


if __name__ == "__main__":
    main()
